#include <iostream>

int main()
{
    std::cout<<"1. QWERTY_\a_QWERTYUJ"<<std::endl;
// Предупреждение (Звуковой сиглан)

    std::cout<<"2. QWERTY_\b_QWERTYUJ"<<std::endl;
// Перемещение курсора на одну позицию назад

    std::cout<<"3. QWERTY_\f_QWERTYUJ"<<std::endl;
// Перемещение курсора к следующей логистической странице

    std::cout<<"4. QWERTY_\n_QWERTYUJ"<<std::endl;
// Перемещение курсора на следующую строку

    std::cout<<"5. QWERTY_\r_QWERTYUJ .5"<<std::endl;
// Перемещение курсора в начало строки

    std::cout<<"6. QWERTY_\t_QWERTYUJ"<<std::endl;
// Вставка горизонтального TAB

    std::cout<<"7. QWERTY_\v_QWERTYUJ"<<std::endl;
// Вставка вертикального TAB

    std::cout<<"8. QWERTY_\'_QWERTYUJ"<<std::endl;
// Вставка одинарной кавычки (или апострофа)

    std::cout<<"9. QWERTY_\"_QWERTYUJ"<<std::endl;
// Вставка двойной кавычки

    std::cout<<"10. QWERTY_\\_QWERTYUJ"<<std::endl;
// Вставка обратной косой черты (бэкслеша)

    std::cout<<"11. QWERTY_\?_QWERTYUJ"<<std::endl;
// Вставка знака вопроса

    std::cout<<"12. QWERTY_\77_QWERTYUJ"<<std::endl;
// Перевод числа из восьмеричной системы счисления в тип char

    std::cout<<"13. QWERTY_\x16_QWERTYUJ"<<std::endl;
// Перевод числа из шестнадцатеричной системы счисления в тип char


    return 0;
}
